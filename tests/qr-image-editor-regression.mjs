import assert from 'node:assert/strict';
import QRCode from 'qrcode';
import {createCanvas, loadImage} from '@napi-rs/canvas';
import {suggestQrCrop, inspectQrCanvas, prepareQrCanvas} from '../scripts/services/qr-image-editor.js';

globalThis.document = {createElement: name => {assert.equal(name, 'canvas'); return createCanvas(1, 1);}};
const payload = 'BETHLEHEM-SYNTHETIC-TEST-ONLY-123456';
const image = await loadImage(await QRCode.toBuffer(payload, {width: 360, margin: 4}));
const original = createCanvas(600, 800);
original.getContext('2d').fillStyle = 'white';
original.getContext('2d').fillRect(0, 0, 600, 800);
original.getContext('2d').drawImage(image, 120, 300);
const found = await inspectQrCanvas(original);
assert.equal(found.data, payload);
const bounds = suggestQrCrop(found, 600, 800);
assert.equal(bounds.width, bounds.height);
assert.ok(bounds.width < 450, 'The suggested square removes surrounding content');
const cropped = createCanvas(Math.round(bounds.width), Math.round(bounds.height));
cropped.getContext('2d').drawImage(original, bounds.x, bounds.y, bounds.width, bounds.height, 0, 0, cropped.width, cropped.height);
const output = await prepareQrCanvas(cropped, found.data);
assert.equal((await inspectQrCanvas(output)).data, payload, 'The final padded crop decodes to the original content');
assert.ok(output.width >= 128 && output.width <= 2048);
const pixels = output.getContext('2d').getImageData(0, 0, output.width, 1).data;
assert.ok([...pixels].every(value => value === 255), 'The output retains a white quiet zone');
const blank = createCanvas(200, 200);
await assert.rejects(prepareQrCanvas(blank), /readable QR/);
const cut = createCanvas(180, 180);
cut.getContext('2d').drawImage(image, -120, -120);
await assert.rejects(prepareQrCanvas(cut, payload), /readable QR/);
await assert.rejects(prepareQrCanvas(cropped, 'DIFFERENT-ACCOUNT'), /different QR/);
await assert.rejects(prepareQrCanvas(createCanvas(100, 100)), /128/);
console.log('Real QR detection, square suggestion, output readability, quiet zone and invalid crop checks passed.');
